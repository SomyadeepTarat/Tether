"""Read-only safety rehearsal: scripted proposals, actual deterministic validator."""
import json
from pathlib import Path
from engine.schemas import AgentAction, GoalContract, Reference
from engine.validator import validate_action


def safety_examples():
    root = Path(__file__).resolve().parents[1]
    contract = GoalContract.model_validate_json((root / 'scenarios/cloud_comparison.json').read_text())
    refs = [Reference.model_validate(r) for r in json.loads((root / 'scenarios/cloud_snapshot.json').read_text())['references']]
    costs = [r for r in refs if r.topic == 'COST']
    content = 'SYNTHETIC_DEMONSTRATION\n' + '\n'.join(f'{r.summary} [{r.reference_id}]' for r in costs)
    base = AgentAction(action_id='preview', project_id=contract.project_id, session_id='preview',
        contract_version=contract.version, milestone_id='M1', topic='COST',
        arguments={'section_id':'cost_preview', 'content':content},
        rationale='Scripted rehearsal proposal; not generated by an agent.',
        declared_effects={'sections_created':['cost_preview'], 'topics_introduced':['COST'],
            'reference_ids_used':[r.reference_id for r in costs],
            'numerical_claims':[{'value':v,'reference_id':r.reference_id,'quote':r.summary} for r in costs for v in r.numerical_values]})
    examples = []
    for title, extra in [('Exact evidence', ''),
                          ('Unsupported interpretation', '\nThis provider is the best choice for your startup.'),
                          ('Unapproved scope', '\nAdd enterprise security compliance analysis.')]:
        proposal = base.model_copy(update={'arguments':base.arguments.model_copy(update={'content':content + extra})})
        result = validate_action(proposal, contract, 'preview', refs)
        examples.append({'title':title, 'proposal':proposal.arguments.content,
            'decision':result.decision, 'reasons':result.reasons or ['Exact supplied quotations with matching evidence and authorized scope.']})
    return {'scripted':True, 'persisted':False, 'provider_calls':0,
            'contract':contract.model_dump(mode='json'), 'examples':examples}
